def build():
    links = '<a href="/about.html">About</a>\n      <a href="/privacy.html">Privacy</a>'
    # render_page runs the page through one more % substitution for the shell's
    # own slots; the body's literal %20 in the mailto is escaped here, after
    # the body's own substitution, the way build_about_page.py does it.
    return render_page(
        pagetitle="How it uses AI", pagesub=SUB, generator=GENERATOR,
        body=body().replace("%", "%%"),
        title=TITLE, desc=DESC, jsonld=jsonld(),
        footerlinks=links, canonical=CANONICAL,
    ).replace("</head>", EXTRA_CSS.strip() + "\n</head>", 1)


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="fail on drift or on a claim that no longer holds, rather "
                         "than writing")
    args = ap.parse_args()

    served = check_served()
    automation = check_automation()
    prs = check_pushes()
    check_signal()
    claims = ("%d served files name no AI service; %d workflow and script files use "
              "none; %d pushing workflows open a pull request and %d push directly, "
              "each recorded; robots.txt's Content-Signal matches"
              % (served, automation, prs, len(DIRECT_PUSH)))

    page = build()
    if page.lower().count("</script") != page.lower().count("<script"):
        fail("the page's script tags do not balance — a literal closing tag in a "
             "comment or string ends the element early")
    current = read(PAGE) if os.path.exists(PAGE) else None
    if args.check:
        if current is None:
            fail("ai.html does not exist. Run `python3 scripts/build_ai_page.py`.")
        if current != page:
            for line in list(difflib.unified_diff(
                    current.split("\n"), page.split("\n"), "shipped", "built",
                    lineterm="", n=1))[:12]:
                print("  " + line)
            fail("ai.html has drifted from its generator. Regenerate rather than "
                 "editing the page.")
        print("build-ai-page: OK — current; " + claims)
        return
    if current == page:
        print("build-ai-page: OK — no change; " + claims)
        return
    with open(PAGE, "w", encoding="utf-8") as fh:
        fh.write(page)
    print("build-ai-page: wrote ai.html; " + claims)


if __name__ == "__main__":
    main()

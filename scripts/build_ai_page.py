#!/usr/bin/env python3
"""
/ai.html — how districtry uses AI: what the coding agents do in building it,
what no AI does, what the person who runs it does, and how the work is checked.
GENERATED on the same shell as /about.html, /privacy.html and /feedback.html.

WHY IT EXISTS (2026-09-23). Most of this repository is written by AI coding
agents, and nothing on the site said so or said where AI stops. A reader
deciding whether to trust a name on a card could not find out that no model
produces the names, or that the person who runs the project does not read
every change. Both are true, and a reader should be told both.

A DRAFT OF THIS PAGE CLAIMED A PERSON APPROVES EVERY CHANGE, AND THAT WAS
FALSE. Since 2026-09-19 a coordinating agent session has held standing
authority from the operator to review and merge the other agents' pull
requests and the weekly roster refreshes; before that, #1024 records a weekly
refresh that put 112 strings that were not names on Rock Island County's
municipal cards for fifteen days. Five commits touching app or roster files
went straight to main without a pull request (two on 2026-09-03, three on
2026-08-24/25), and the deploy smoke-tests the Illinois app alone. So the page
claims none of: a person reviews every change, every change is a pull
request, every app is browser-tested before a deploy. It says what is true.

WHY IT IS GENERATED WHEN IT CARRIES NO NUMBER. The prose is fixed, but the
shell is not: tokens, fonts, favicon, footer byline and the counter move with
the other root pages, and a hand-written copy of that shell is how a page falls
out of step with them. The generator exists for the shell and for the checks
below; the prose is written here, once.

NO NUMBERS, DELIBERATELY. The page states no count, share or date. Every
number about this project moves weekly, and a page about how the project is
run should not carry a figure that is wrong a fortnight later. It links the
commit history instead.

WHAT IT CHECKS, because each is a claim the page makes:

  1. No served file calls an AI service. Every .html and .js file outside the
     build-only folders is searched for the API hosts of the known AI
     services. This is a DENYLIST: it cannot prove that an unknown host is not
     one. The complete list of what a browser contacts is the privacy page's
     recipients table, which build_privacy_page.py measures.
  2. No workflow, and no script a workflow can run, uses an AI service: the
     same hosts, plus AI actions, SDK imports, the Claude CLI's print mode and
     AI API-key names. This backs "the weekly updates are read by ordinary
     code". This file is the one script excluded, because it names them.
  3. A workflow that pushes opens a pull request. Every workflow running
     `git push` must also run `gh pr create`, unless DIRECT_PUSH records why
     not. Each entry there FAILS when its file is gone, no longer pushes, or
     has started opening a pull request, so the list cannot rot. /about.html
     makes the same claim ("opens a pull request rather than committing").
  4. robots.txt still says what the page says about AI systems reading the
     site: the Content-Signal for `*`, read by robots_policy.py.

WHAT IT CANNOT CHECK. Who reviews and merges a pull request is not recorded in
the tree, and neither is the traffic report being refreshed by a scheduled
agent. The page states both as the project's practice; a change to that
practice is a change to the prose here.

    python3 scripts/build_ai_page.py           # write ai.html
    python3 scripts/build_ai_page.py --check   # drift gate + the four checks
"""


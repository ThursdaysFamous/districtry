#!/usr/bin/env python3
"""Generate the link-preview page a shared map link opens first: one per app and layer.

    python3 scripts/build_share_pages.py            # write <tag>/s/<code>/index.html
    python3 scripts/build_share_pages.py --check    # drift gate; exit 1 on any difference

WHY THESE PAGES EXIST (Adam, 2026-11-17, choosing "Layer words" over a picture
per layer and over a preview made on the fly). A shared map link names its place
and its layers after the `#`, and the apps that draw a link preview — Messages,
Slack, Facebook, Signal — never read that part: a browser does not send the
fragment to a server, and a preview bot runs no script. So every shared link
showed the same preview, the app's general title and its brand card, whatever
the sender had on. That is deliberate and stays: the fragment is what keeps a
reader's exact selected point off every server, ours included, on a site whose
standard is that a point is rounded to two decimals before anything is sent.

What CAN move into the part of the address a server sees is the LAYER, which
says nothing about where anybody is. So the share control (engine `permalink`,
`shareLinkUrl`) writes `/<tag>/s/<code>/?ref=share#p=…&l=…` instead of
`/<tag>/?ref=share#p=…&l=…`, where <code> is one layer's permanent link code
from the root `layer-codes.json`, and this script writes the page that address
serves: a head carrying a title, description and image naming that layer and
that state, and a script that replaces itself with the app at once, keeping the
query and the fragment, so the reader lands on the same view the old link
opened. With no fragment (somebody typed the address) it opens the app with
that layer on. A reader with scripts off gets a link to the map.

THE POINT IS NEVER IN THE PREVIEW AND NEVER IN THE PATH. A preview naming the
district or the person in it ("Ward 33") would need the district in the part
of the link servers see, and was offered to Adam and not chosen.

ONE PAGE PER LAYER, NOT PER COMBINATION. A link can carry any set of layers, and
a page per set is unbounded, so the share control names ONE: the layer pinned
for comparison when there is one, otherwise the most local layer on (last in
LAYER_AREA_RANK). The description says the map opens with the layers the
sender had on, which is true of every set.

WHAT A PAGE CARRIES AND DOES NOT:
  * noindex, and no canonical. It is not a page to find by searching, and
    build_sitemap.py includes a page only on its canonical (it also globs no
    deeper than <tag>/*/*.html, and these sit at <tag>/s/<code>/index.html).
  * og:url naming ITSELF. Facebook re-reads the address og:url gives, so a page
    pointing it at the app would hand Facebook the app's general preview.
  * the app's own card image (<tag>/og-image.png, scripts/build_og_image.mjs).
    A picture per layer was option 2 and is not built.
  * NO GoatCounter tag. The page leaves before the counter could send, and the
    app it opens counts the visit with its `ref=share`. validate_analytics.py
    records the whole set as one exception (NO_COUNTER_PATTERNS), and the
    privacy page names it.
  * no request to any host. Everything is inline.

EVERY WORKSHEET LAYER GETS A PAGE, dark instances included: a dark folder is
excluded from the deploy whole, so its pages publish the day it goes live, and
the share control can assume a page exists for every coded layer. --check fails
on a missing page, a page that differs from what this writes, and a page under
s/ that no worksheet layer accounts for (a retired layer's page would otherwise
go on answering unchecked). A retired layer's CODE stays in layer-codes.json
forever; its page goes, and an old link to it gets GitHub Pages' 404 — accepted,
because a preview page outliving its layer would describe a layer the app no
longer draws.
"""

import argparse
import html
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CODES_PATH = os.path.join(REPO, "layer-codes.json")
MARK = "GENERATED by scripts/build_share_pages.py"

# Labels written for a sidebar toggle, rewritten for a sentence. Everything not
# named here passes through the two rules in preview_label().
LABEL_OVERRIDES = {
    "CPS Network (High School, admin office)": "CPS High School Network",
    "CPS Network (K-8, admin office)": "CPS K-8 Network",
    "School Location (all, incl. private, nearest N)": "School Location",
}
SCHOOL_KIND = re.compile(r"^(.*) \((Elementary|Secondary|Unified|Union High)\)$")
ACRONYM = re.compile(r" \([A-Z0-9]{2,}\)")


def fail(msg):
    print("build-share-pages: FAIL — %s" % msg, file=sys.stderr)
    sys.exit(1)


def preview_label(label):
    if label in LABEL_OVERRIDES:
        return LABEL_OVERRIDES[label]
    m = SCHOOL_KIND.match(label)
    if m:
        return "%s %s" % (m.group(2), m.group(1))
    return ACRONYM.sub("", label)


def instances():
    """A top-level directory with an index.html and a data/app is an instance,
    the rule validate_instance_registration.py discovers by. Illinois's
    worksheet sits at the repo root."""
    out = []
    for name in sorted(os.listdir(REPO)):
        if not (os.path.isdir(os.path.join(REPO, name, "data", "app"))
                and os.path.exists(os.path.join(REPO, name, "index.html"))):
            continue
        ws = os.path.join(REPO, "metro-worksheet.json" if name == "il"
                          else os.path.join(name, "metro-worksheet.json"))
        if not os.path.exists(ws):
            fail("%s/ is an instance with no worksheet at %s"
                 % (name, os.path.relpath(ws, REPO)))
        out.append((name, ws))
    if len(out) < 2:
        fail("found %d instance(s); the tree walk is wrong" % len(out))
    return out


def host():
    with open(os.path.join(REPO, "CNAME"), encoding="utf-8") as f:
        name = f.read().strip()
    if not name:
        fail("CNAME is empty")
    return name


def page(tag, app_name, place, layer, code, origin):
    e = lambda s: html.escape(s, quote=True)
    label = preview_label(layer["label"])
    url = "%s/%s/s/%s/" % (origin, tag, code)
    image = "%s/%s/og-image.png" % (origin, tag)
    title = "%s map of %s · districtry" % (label, place)
    desc = ("Opens the shared place on the %s map with the %s layer on, and the "
            "other layers the sender had on. districtry shows every district "
            "that covers a place, and who represents you there." % (place, label))
    alt = "The districtry logo, labelled %s" % tag
    # The forward: the app is two levels up. The query (?ref=share) and the
    # fragment pass through unchanged; with no fragment the layer is turned on.
    script = (
        "(function(){var h=location.hash;"
        "location.replace('../../'+location.search+(h&&h.length>1?h:'#l=%s'));"
        "})();" % code)
    return "\n".join([
        "<!doctype html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8" />',
        "<!-- %s: the link preview for the %s layer. Do not hand-edit. -->"
        % (MARK, e(layer["id"])),
        "<script>%s</script>" % script,
        '<meta name="viewport" content="width=device-width, initial-scale=1" />',
        '<meta name="color-scheme" content="light dark" />',
        '<meta name="robots" content="noindex" />',
        "<title>%s</title>" % e(title),
        '<meta name="description" content="%s" />' % e(desc),
        '<meta property="og:type" content="website" />',
        '<meta property="og:site_name" content="%s" />' % e(app_name),
        '<meta property="og:title" content="%s" />' % e(title),
        '<meta property="og:description" content="%s" />' % e(desc),
        '<meta property="og:url" content="%s" />' % e(url),
        '<meta property="og:image" content="%s" />' % e(image),
        '<meta property="og:image:width" content="1200" />',
        '<meta property="og:image:height" content="630" />',
        '<meta property="og:image:alt" content="%s" />' % e(alt),
        '<meta property="og:locale" content="en_US" />',
        '<meta name="twitter:card" content="summary_large_image" />',
        '<meta name="twitter:title" content="%s" />' % e(title),
        '<meta name="twitter:description" content="%s" />' % e(desc),
        '<meta name="twitter:image" content="%s" />' % e(image),
        "</head>",
        "<body>",
        '<p><a href="../../#l=%s">Open the %s map with the %s layer on</a></p>'
        % (e(code), e(place), e(label)),
        "</body>",
        "</html>",
        "",
    ])


def expected():
    with open(CODES_PATH, encoding="utf-8") as f:
        codes = json.load(f)["codes"]
    origin = "https://" + host()
    out = {}
    for tag, ws in instances():
        with open(ws, encoding="utf-8") as f:
            w = json.load(f)
        app_name = (w.get("brand") or {}).get("app_name") or ""
        if not app_name.startswith("districtry "):
            fail("%s: brand.app_name %r does not start with 'districtry ', so the "
                 "place name cannot be read from it" % (tag, app_name))
        place = app_name[len("districtry "):]
        for layer in w["layers"]:
            code = codes.get(layer["id"])
            if not code:
                fail("%s: layer %s has no code in layer-codes.json "
                     "(generate_metro_files.py should already refuse this)"
                     % (tag, layer["id"]))
            if not re.fullmatch(r"[a-z][a-z0-9]{1,2}", code):
                fail("%s: layer %s has code %r, which is not a safe path segment"
                     % (tag, layer["id"], code))
            rel = os.path.join(tag, "s", code, "index.html")
            out[rel] = page(tag, app_name, place, layer, code, origin)
    return out


def on_disk():
    found = set()
    for tag, _ws in instances():
        root = os.path.join(REPO, tag, "s")
        if not os.path.isdir(root):
            continue
        for dirpath, _dirs, files in os.walk(root):
            for name in files:
                found.add(os.path.relpath(os.path.join(dirpath, name), REPO))
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    want = expected()
    have = on_disk()
    stray = sorted(have - set(want))

    if args.check:
        problems = []
        for rel, text in sorted(want.items()):
            path = os.path.join(REPO, rel)
            if not os.path.exists(path):
                problems.append("%s is missing" % rel)
                continue
            with open(path, encoding="utf-8") as f:
                if f.read() != text:
                    problems.append("%s differs from what this script writes" % rel)
        for rel in stray:
            problems.append("%s is under s/ and no worksheet layer accounts for it"
                            % rel)
        if problems:
            shown = problems[:20]
            more = len(problems) - len(shown)
            fail("%d problem(s):\n  %s%s\nRun python3 scripts/build_share_pages.py "
                 "to regenerate." % (len(problems), "\n  ".join(shown),
                                     "\n  … and %d more" % more if more else ""))
        print("build-share-pages: OK — %d link-preview page(s) across %d instance(s) "
              "match what this script writes"
              % (len(want), len({r.split(os.sep)[0] for r in want})))
        return

    for rel in stray:
        os.remove(os.path.join(REPO, rel))
        try:
            os.removedirs(os.path.dirname(os.path.join(REPO, rel)))
        except OSError:
            pass
    written = 0
    for rel, text in sorted(want.items()):
        path = os.path.join(REPO, rel)
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                old = f.read()
        if old != text:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            written += 1
    print("build-share-pages: %d page(s), %d written, %d stray removed"
          % (len(want), written, len(stray)))


if __name__ == "__main__":
    main()

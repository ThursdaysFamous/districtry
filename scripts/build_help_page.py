#!/usr/bin/env python3
"""
/help.html — how to use districtry: find a place, choose the kinds of district
to show, read the cards, compare, share, the phone app, and what to do when an
answer is missing or wrong. GENERATED on the same shell as /about.html,
/privacy.html, /ai.html and /feedback.html.

WHY IT EXISTS (2026-10-28). The first two reviews from the Google Play closed
test said the map "works but needs a tutorial" and is "biraz karmaşık" (a bit
complicated). Adam chose a one-time tip on every map with an optional short
tour (engine `first-use`) and this page, linked from each map's masthead as
"How to use" and from the tip. He ruled out switching layers on for a new
reader, because a layer the app switched on would be counted as one a reader
chose, so the page tells a reader to tick one and switches nothing on.

ONE PAGE FOR EVERY STATE, at the root, because the map works the same way in
all of them. Where an app differs (the Bulk Address Checker and the search by
district name are Illinois's, and people counts in the comparison report are
Illinois's), the page says which app has it, and CHECK 2 below holds those
sentences to the tree.

NO PICTURES, DELIBERATELY. A screenshot of a card carries an officeholder's
name, which goes out of date at the next election, and a picture of the map
carries a layout that moves with each change to the masthead. The page names
each control by the words on it instead, and CHECK 1 holds those words.

NO NUMBERS. Like /ai.html, the page states no count: the number of states,
layers and counties moves weekly.

WHAT IT CHECKS, because each is a claim the page makes:

  1. Every control the page names by its label is still labelled that way.
     LABELS maps each quoted label to the files that must carry it: the
     engine blocks every app composes, or one app's own index.html. A label
     renamed in the app without this page changing FAILS.
  2. The controls the page says only some apps have are only in those apps.
     ONLY_IN lists each with the apps the page names; an app gaining or
     losing it FAILS, so the sentence naming the apps cannot go stale.

    python3 scripts/build_help_page.py           # write help.html
    python3 scripts/build_help_page.py --check   # drift gate + the two checks
"""

import argparse

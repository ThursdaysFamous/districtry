def build():
    links = ('<a href="/about.html">About</a>\n      <a href="/privacy.html">Privacy</a>\n'
             '      <a href="/ai.html">How it uses AI</a>')
    return render_page(
        pagetitle="How to use", pagesub=SUB, generator=GENERATOR,
        body=body().replace("%", "%%"),
        title=TITLE, desc=DESC, jsonld=jsonld(),
        footerlinks=links, canonical=CANONICAL,
    ).replace("</head>", EXTRA_CSS.strip() + "\n</head>", 1)


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="fail on drift or on a control renamed, rather than writing")
    args = ap.parse_args()

    tags = apps()
    if len(tags) < 2:
        fail("found %d app folders; expected the fleet" % len(tags))
    labels = check_labels(tags)
    only = check_only_in(tags)
    claims = "%d control labels hold; %d single-app sentences hold" % (labels, only)

    page = build()
    current = read(PAGE) if os.path.exists(PAGE) else None
    if args.check:
        if current is None:
            fail("help.html does not exist. Run `python3 scripts/build_help_page.py`.")
        if current != page:
            for line in list(difflib.unified_diff(
                    current.split("\n"), page.split("\n"), "shipped", "built",
                    lineterm="", n=1))[:12]:
                print("  " + line)
            fail("help.html has drifted from its generator. Regenerate rather than "
                 "editing the page.")
        print("build-help-page: OK — current; " + claims)
        return
    if current == page:
        print("build-help-page: OK — no change; " + claims)
        return
    with open(PAGE, "w", encoding="utf-8") as fh:
        fh.write(page)
    print("build-help-page: wrote help.html; " + claims)


if __name__ == "__main__":
    main()

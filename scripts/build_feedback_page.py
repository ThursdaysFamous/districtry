#!/usr/bin/env python3
"""
/feedback.html — the "report a bug or leave a comment" form for every page
that is not a map app. GENERATED on the same shell as /about.html and
/privacy.html.

WHY IT EXISTS. The six apps carry this form in a dialog, and nothing else on
the site did: a reader on a county board page, a question page or the front
door who found a wrong name had a hello@ address in the footer and no form. It
also had no LINK — the app's dialog opened from a button and nowhere else, so
there was no address to hand a tester. Now:

  - every page's footer byline (engine/shared/footer-byline.txt) links here;
  - the apps open their own dialog from `#feedback` or `#feedback=<text>`
    (engine/index.html/feedback.txt), which keeps the point and layers the
    report is about;
  - this page reads the same `#feedback=<text>`, plus `#page=<address>` for
    the page being reported. With no `page=` it takes the address the reader
    came from, when that is on this site.

THE HASH, NOT THE QUERY STRING. GoatCounter sends location.search with every
hit, so a `?feedback=` would put what a reader wrote into the analytics record.
The fragment never leaves the browser. Nothing on this page is sent anywhere
until the reader presses one of the two send buttons, which open a GitHub issue
or an e-mail draft for them to review — the same two routes the apps offer, to
the same repository and the same address.

    python3 scripts/build_feedback_page.py           # write feedback.html
    python3 scripts/build_feedback_page.py --check   # the CI drift gate
"""

import argparse
import difflib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from build_privacy_page import (  # noqa: E402
    CONTACT, REPO_URL, SITE, esc, render_page,
)

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGE = os.path.join(REPO_ROOT, "feedback.html")
CANONICAL = SITE + "feedback.html"
METROS = os.path.join(REPO_ROOT, "metros.json")

TITLE = "Report a problem or leave a comment — districtry"
DESC = ("Tell districtry about a wrong district, a wrong name or a broken page, "
        "or leave a comment. Sent as a GitHub issue or an e-mail you review first.")
SUB = "Found something wrong, or have a suggestion? Say what and where."
GENERATOR = (
    "<!-- GENERATED by scripts/build_feedback_page.py. `--check` fails when this\n"
    "     file and the script disagree. Do NOT hand-edit. -->")
ISSUES = REPO_URL + "/issues/new"
SUBJECT = "districtry feedback"


def fail(msg):
    print("build-feedback-page: FAIL — %s" % msg, file=sys.stderr)
    sys.exit(1)


def fleet():
    """The apps, from metros.json, for the footer links and the note on
    reporting a map view. Read, never listed here."""
    with open(METROS, encoding="utf-8") as fh:
        data = json.load(fh)
    rows = data.get("metros") if isinstance(data, dict) else data
    out = []
    for m in rows or []:
        url, name = m.get("url"), m.get("landing_name") or m.get("name")
        if url and name:
            out.append({"url": url, "name": name})
    if len(out) < 2:
        fail("metros.json lists fewer than two apps — is it still the fleet list?")
    return out


def jsonld():
    return json.dumps({
        "@context": "https://schema.org",
        "@type": "ContactPage",
        "@id": CANONICAL,
        "url": CANONICAL,
        "name": TITLE,
        "description": DESC,
        "inLanguage": "en-US",
        "isPartOf": {"@id": SITE + "#website"},
        "breadcrumb": {
            "@type": "BreadcrumbList",
            "itemListElement": [
                {"@type": "ListItem", "position": 1, "name": "districtry", "item": SITE},
                {"@type": "ListItem", "position": 2, "name": "Report a problem"},
            ],
        },
    }, indent=2)


# The form's own styles, in the shell's token vocabulary.
